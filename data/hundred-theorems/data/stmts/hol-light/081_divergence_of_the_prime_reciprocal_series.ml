(* ========================================================================= *)
(* Divergence of prime reciprocal series.                                    *)
(* ========================================================================= *)

(* ------------------------------------------------------------------------- *)
(* Now load other stuff needed.                                              *)
(* ------------------------------------------------------------------------- *)

needs "100/bertrand.ml";;
needs "100/divharmonic.ml";;

(* ------------------------------------------------------------------------- *)
(* Variant of induction.                                                     *)
(* ------------------------------------------------------------------------- *)

let INDUCTION_FROM_1 = `!P. P 0 /\ P 1 /\ (!n. 1 <= n /\ P n ==> P(SUC n)) ==> !n. P n`;;

(* ------------------------------------------------------------------------- *)
(* Evaluate sums over explicit intervals.                                    *)
(* ------------------------------------------------------------------------- *)

let SUM_CONV =
  let pth = `sum(1..1) f = f 1 /\ sum(1..SUC n) f = sum(1..n) f + f(SUC n)`;;

(* ------------------------------------------------------------------------- *)
(* Hence an overall lower bound.                                             *)
(* ------------------------------------------------------------------------- *)

let PRIMERECIP_LBOUND = `!n. &3 / (&32 * ln(&32)) * &n
       <= sum (1 .. 32 EXP (2 EXP n)) (\i. if prime i then &1 / &i else &0)`;;

(* ------------------------------------------------------------------------- *)
(* General lemma.                                                            *)
(* ------------------------------------------------------------------------- *)

let UNBOUNDED_DIVERGENT = `!s. (!k. ?N. !n. n >= N ==> sum(1..n) s >= k)
       ==> ~(convergent(\n. sum(1..n) s))`;;

(* ------------------------------------------------------------------------- *)
(* Hence divergence.                                                         *)
(* ------------------------------------------------------------------------- *)

let PRIMERECIP_DIVERGES_NUMSEG = `~(convergent (\n. sum (1..n) (\i. if prime i then &1 / &i else &0)))`;;

(* ------------------------------------------------------------------------- *)
(* A perhaps more intuitive formulation.                                     *)
(* ------------------------------------------------------------------------- *)

let PRIMERECIP_DIVERGES = `~(convergent (\n. sum {p | prime p /\ p <= n} (\p. &1 / &p)))`;;
